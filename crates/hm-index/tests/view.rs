//! The read module the panel uses (`hm_index::view`): map facts, indexed files, search.

mod common;

use std::fs;

use hm_index::index::Indexer;
use hm_index::view::{Hit, MapLink, indexed_file, map_facts, search};
use hm_store::Store;

/// A temporary project holding `files` (path, text), indexed once. The `TempDir` comes
/// last: drop the indexer first, as in `common::indexed`.
fn project(files: &[(&str, &str)]) -> (Indexer, tempfile::TempDir) {
    let dir = tempfile::tempdir().expect("create a temporary directory");
    for (rel, text) in files {
        let path = dir.path().join(rel);
        fs::create_dir_all(path.parent().unwrap()).expect("create folders");
        fs::write(path, text).expect("write a file");
    }
    let store = Store::open_in_memory().expect("open a store");
    let mut ix = Indexer::open(dir.path(), store).expect("open the indexer");
    ix.full().expect("index the project");
    (ix, dir)
}

/// The paths of `files` in map order.
fn paths(ix: &Indexer) -> Vec<String> {
    map_facts(ix.store())
        .unwrap()
        .files
        .into_iter()
        .map(|f| f.path)
        .collect()
}

/// Links as (source path, destination path, refs).
fn links(ix: &Indexer) -> Vec<(String, String, u32)> {
    let facts = map_facts(ix.store()).unwrap();
    facts
        .links
        .iter()
        .map(|l| {
            (
                facts.files[l.src as usize].path.clone(),
                facts.files[l.dst as usize].path.clone(),
                l.refs,
            )
        })
        .collect()
}

fn link(src: &str, dst: &str, refs: u32) -> (String, String, u32) {
    (src.to_string(), dst.to_string(), refs)
}

#[test]
fn map_facts_lists_source_files_and_counts_the_rest() {
    let (ix, _dir) = project(&[
        (
            "src/orders/service.ts",
            "export function place() { return 1; }\n",
        ),
        (
            "src/orders/service.test.ts",
            "import { place } from './service';\nplace();\n",
        ),
        ("README.md", "# Shop\n"),
    ]);
    let facts = map_facts(ix.store()).unwrap();

    assert_eq!(facts.files.len(), 1);
    let service = &facts.files[0];
    assert_eq!(service.path, "src/orders/service.ts");
    assert_eq!(service.lang.as_deref(), Some("typescript"));
    assert_eq!(service.loc, 1);
    assert!(!service.generated);
    assert_eq!(facts.excluded.get("test"), Some(&1));
    assert_eq!(facts.excluded.get("doc"), Some(&1));
    assert_eq!(facts.excluded.len(), 2);
    // The test file is not on the map, so its link to the service is dropped.
    assert!(facts.links.is_empty());
}

#[test]
fn generated_files_are_on_the_map_and_flagged() {
    let (ix, _dir) = project(&[
        ("src/b.ts", "export const b = 1;\n"),
        (
            "src/a.generated.ts",
            "// Code generated by shop-gen. DO NOT EDIT.\nexport const a = 1;\n",
        ),
    ]);
    let facts = map_facts(ix.store()).unwrap();
    let got: Vec<(&str, bool)> = facts
        .files
        .iter()
        .map(|f| (f.path.as_str(), f.generated))
        .collect();
    // Sorted by path.
    assert_eq!(got, [("src/a.generated.ts", true), ("src/b.ts", false)]);
}

#[test]
fn links_count_calls_and_fall_back_to_one_for_bare_imports() {
    let (ix, _dir) = project(&[
        (
            "a.ts",
            "import { first, second } from './b';\nimport type { Total } from './c';\n\
             export function run(): Total | undefined {\n  first();\n  second();\n  return undefined;\n}\n",
        ),
        (
            "b.ts",
            "export function first() {}\nexport function second() {}\n",
        ),
        ("c.ts", "export type Total = number;\n"),
    ]);
    assert_eq!(
        links(&ix),
        [link("a.ts", "b.ts", 2), link("a.ts", "c.ts", 1)]
    );
}

#[test]
fn links_count_extends_with_calls_and_are_sorted_by_index() {
    let (ix, _dir) = project(&[
        (
            "a.ts",
            "import { Base, helper } from './b';\n\
             export class Cart extends Base {}\n\
             export function run() { helper(); }\n",
        ),
        (
            "b.ts",
            "export class Base {}\nexport function helper() {}\n",
        ),
        ("c.ts", "import { run } from './a';\nrun();\n"),
    ]);
    let facts = map_facts(ix.store()).unwrap();
    assert_eq!(
        links(&ix),
        [link("a.ts", "b.ts", 2), link("c.ts", "a.ts", 1)]
    );
    // `src` and `dst` index into `files`, and the list is sorted by (src, dst).
    let ordered: Vec<(u32, u32)> = facts
        .links
        .iter()
        .map(|l: &MapLink| (l.src, l.dst))
        .collect();
    let mut sorted = ordered.clone();
    sorted.sort();
    assert_eq!(ordered, sorted);
}

#[test]
fn self_links_and_external_packages_are_dropped() {
    let (ix, _dir) = project(&[
        (
            "a.ts",
            "import { z } from 'zod';\nfunction inner() {}\nexport function outer() { inner(); }\n",
        ),
        ("b.ts", "export const b = 1;\n"),
    ]);
    assert_eq!(paths(&ix), ["a.ts", "b.ts"]);
    assert!(links(&ix).is_empty());
}

#[test]
fn indexed_file_knows_only_rows_in_the_store() {
    let (ix, dir) = project(&[
        (".gitignore", "secret.ts\n"),
        ("secret.ts", "export const k = 1;\n"),
        ("src/shop.ts", "export const s = 1;\n"),
    ]);
    assert!(dir.path().join("secret.ts").is_file());

    let shop = indexed_file(ix.store(), "src/shop.ts")
        .unwrap()
        .expect("the file is indexed");
    assert_eq!(shop.path, "src/shop.ts");
    assert_eq!(shop.lang.as_deref(), Some("typescript"));
    assert_eq!(shop.class, "source");

    assert_eq!(indexed_file(ix.store(), "secret.ts").unwrap(), None);
    assert_eq!(indexed_file(ix.store(), "src/missing.ts").unwrap(), None);
}

#[test]
fn search_ranks_exact_names_first_and_treats_percent_literally() {
    let (ix, _dir) = project(&[
        ("src/cart.ts", "export const a = 1;\n"),
        ("src/cart-view.ts", "export const b = 1;\n"),
        ("src/discount%.ts", "export const c = 1;\n"),
    ]);
    let files = |q: &str| -> Vec<String> {
        search(ix.store(), q, 10)
            .unwrap()
            .into_iter()
            .filter(|h| h.kind == "file")
            .map(|h| h.path)
            .collect()
    };
    assert_eq!(files("cart"), ["src/cart.ts", "src/cart-view.ts"]);
    assert_eq!(files("CART"), ["src/cart.ts", "src/cart-view.ts"]);
    assert_eq!(files("%"), ["src/discount%.ts"]);
    // `_` is literal too: it must not match every character.
    assert!(files("_").is_empty());
}

#[test]
fn search_finds_symbols_after_files_and_honours_the_limit() {
    let (ix, _dir) = project(&[
        (
            "src/orders.ts",
            "export class Cart { total() { return 0; } }\nexport function cartSize() { return 1; }\n",
        ),
        ("src/cart.ts", "export const x = 1;\n"),
    ]);
    let hits = search(ix.store(), "cart", 10).unwrap();
    let got: Vec<(&str, &str, Option<&str>)> = hits
        .iter()
        .map(|h| (h.kind, h.path.as_str(), h.symbol.as_deref()))
        .collect();
    assert_eq!(
        got,
        [
            ("file", "src/cart.ts", None),
            ("symbol", "src/orders.ts", Some("Cart")),
            ("symbol", "src/orders.ts", Some("Cart.total")),
            ("symbol", "src/orders.ts", Some("cartSize")),
        ]
    );

    // Methods are searched as `Owner.name`.
    let hits = search(ix.store(), "Cart.tot", 10).unwrap();
    assert_eq!(
        hits,
        [Hit {
            kind: "symbol",
            path: "src/orders.ts".into(),
            symbol: Some("Cart.total".into())
        }]
    );

    assert_eq!(search(ix.store(), "cart", 2).unwrap().len(), 2);
    // The limit counts files and symbols together.
    assert_eq!(search(ix.store(), "cart", 1).unwrap()[0].kind, "file");
    assert!(search(ix.store(), "cart", 0).unwrap().is_empty());
}

#[test]
fn empty_and_blank_queries_find_nothing() {
    let (ix, _dir) = project(&[("src/cart.ts", "export const x = 1;\n")]);
    assert!(search(ix.store(), "", 10).unwrap().is_empty());
    assert!(search(ix.store(), "  \t", 10).unwrap().is_empty());
}
